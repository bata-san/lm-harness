#Requires -RunAsAdministrator
<#
.SYNOPSIS
  Windows 側を LLM 推論向けにチューニングし、.wslconfig を生成する。

.DESCRIPTION
  - WSL を最新化
  - 電源プラン「究極のパフォーマンス」を有効化 (CPU のクロック落ち/コアパーキングを防ぐ)
  - ハードウェア アクセラレータによる GPU スケジューリング (HAGS) を有効化
  - %UserProfile%\.wslconfig を生成 (メモリ/CPU を WSL に最大限割り当て、mirrored ネットワーク)
  - mirrored モードで Windows/LAN からハーネスに届くよう Hyper-V ファイアウォールを許可
  - (任意) Defender のリアルタイムスキャンから WSL の VHDX を除外

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\windows\setup-host.ps1
  powershell -ExecutionPolicy Bypass -File scripts\windows\setup-host.ps1 -MemoryPercent 85 -DefenderExclusion
#>
param(
    [int]$MemoryPercent = 85,      # 物理メモリのうち WSL に渡す割合
    [int]$SwapGB = 32,
    [switch]$DefenderExclusion,
    [switch]$NoShutdown
)

$ErrorActionPreference = "Stop"
function Step($m) { Write-Host "==> $m" -ForegroundColor Cyan }

Step "WSL を更新"
wsl --update | Out-Host
wsl --set-default-version 2 | Out-Null

Step "電源プラン: 究極のパフォーマンス"
$ultimate = "e9a42b02-d5df-448d-aa00-03f14749eb61"
$existing = powercfg /list | Select-String "\(Ultimate Performance\)|\(究極のパフォーマンス\)"
if (-not $existing) {
    $out = powercfg -duplicatescheme $ultimate
    $guid = ([regex]'[0-9a-f-]{36}').Match($out).Value
} else {
    $guid = ([regex]'[0-9a-f-]{36}').Match($existing.ToString()).Value
}
powercfg /setactive $guid
# PCIe リンクステート省電力を無効化 (GPU のレイテンシ対策)
powercfg /setacvalueindex $guid SUB_PCIEXPRESS ASPM 0
powercfg /setactive $guid

Step "GPU ハードウェアスケジューリング (HAGS) を有効化 (再起動後に反映)"
New-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Control\GraphicsDrivers" -Name HwSchMode -Value 2 -PropertyType DWord -Force | Out-Null

Step "NVIDIA ドライバ確認"
try { nvidia-smi --query-gpu=name,driver_version,memory.total,compute_cap --format=csv | Out-Host }
catch { Write-Warning "nvidia-smi が見つかりません。NVIDIA の Windows 用ドライバ (Studio / RTX Enterprise) を入れてください" }

Step ".wslconfig を生成"
$totalGB = [math]::Floor((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB)
$memGB = [math]::Max(8, [math]::Floor($totalGB * $MemoryPercent / 100))
$procs = (Get-CimInstance Win32_Processor | Measure-Object -Property NumberOfLogicalProcessors -Sum).Sum
$wslconfig = Join-Path $env:USERPROFILE ".wslconfig"
if (Test-Path $wslconfig) { Copy-Item $wslconfig "$wslconfig.bak" -Force }
@"
# Generated by llm-harness scripts/windows/setup-host.ps1
[wsl2]
# 物理 ${totalGB}GB のうち ${MemoryPercent}% を WSL へ。大きいモデルの CPU オフロード/ページキャッシュ用
memory=${memGB}GB
# Threadripper の全論理コアを WSL へ
processors=${procs}
swap=${SwapGB}GB
# Windows の localhost / LAN と同じネットワークを共有 (ポート転送不要)
networkingMode=mirrored
dnsTunneling=true
autoProxy=true
firewall=true

[experimental]
# モデルのページキャッシュを WSL が勝手に解放しないようにする (再ロードが遅くなるのを防ぐ)
autoMemoryReclaim=disabled
# VHDX を自動で縮小 (モデル削除後のディスクを回収)
sparseVhd=true
hostAddressLoopback=true
"@ | ForEach-Object { [IO.File]::WriteAllText($wslconfig, $_, (New-Object Text.UTF8Encoding $false)) }
Write-Host "   memory=${memGB}GB processors=${procs} -> $wslconfig"

Step "Hyper-V ファイアウォール: WSL への受信を許可 (mirrored モード用)"
try {
    Set-NetFirewallHyperVVMSetting -Name '{40E0AC32-46A5-438A-A0B2-2B479E8F2E90}' -DefaultInboundAction Allow
} catch { Write-Warning "Hyper-V ファイアウォール設定をスキップ: $_" }

if ($DefenderExclusion) {
    Step "Defender: WSL VHDX と vmmem をスキャン除外"
    $pkgs = Join-Path $env:LOCALAPPDATA "Packages"
    Get-ChildItem $pkgs -Directory -Filter "*CanonicalGroupLimited*" -ErrorAction SilentlyContinue | ForEach-Object {
        Add-MpPreference -ExclusionPath (Join-Path $_.FullName "LocalState")
        Write-Host "   excluded $($_.FullName)\LocalState"
    }
    Add-MpPreference -ExclusionProcess "vmmem", "vmmemWSL", "wslhost.exe"
}

if (-not $NoShutdown) {
    Step "WSL を再起動して設定を反映"
    wsl --shutdown
}

Write-Host ""
Write-Host "完了。HAGS は Windows 再起動後に有効になります。" -ForegroundColor Green
Write-Host "次: WSL (Ubuntu) で  bash scripts/wsl/setup.sh  を実行"
